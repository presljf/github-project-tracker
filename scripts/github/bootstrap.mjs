#!/usr/bin/env node
/**
 * Config-driven, idempotent tracker bootstrap.
 *
 * Default is dry-run; pass --apply to mutate. Never deletes user data.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateConfig } from './validate-config.mjs';
import { createGitHub } from './lib/github.mjs';
import { UsageError, parseArgs } from './lib/cli.mjs';

const DEFAULT_CONFIG = 'tracker.config.json';

export function buildIssueSpecs(config) {
  const specs = [];
  const roadmapTitle = config.roadmap ? `[Roadmap] ${config.roadmap.title || 'Program roadmap'}` : null;
  if (roadmapTitle) {
    specs.push({
      kind: 'roadmap',
      title: roadmapTitle,
      parentTitle: null,
      milestone: null,
      release: null,
      sprint: null,
      body: config.roadmap.body || '# Program roadmap\n\nRelease and sprint plan of record.\n',
    });
  }
  for (const release of config.releases || []) {
    const releaseTitle = `[Release] ${release.key}`;
    specs.push({
      kind: 'release',
      title: releaseTitle,
      parentTitle: roadmapTitle,
      milestone: release.milestone,
      release: release.key,
      sprint: null,
      body: [
        `# Release ${release.key}`,
        '',
        `**Milestone:** ${release.milestone}`,
        '',
        '## Release objective',
        '',
        '- Skeleton generated by bootstrap. Define scope, gates, risks, artifacts, and rollback before kickoff.',
        '',
        '## Sprint scope',
        '',
        ...((release.sprints || []).map((sprint) => `- [ ] ${sprint.key} — ${sprint.title}`).join('\n') || ['- TBD']),
        '',
        '## Release gates',
        '',
        '- [ ] Required checks green',
        '- [ ] Artifacts/checksums/version verified',
        '- [ ] Docs/release notes updated',
        '- [ ] Rollback documented',
        '',
      ].join('\n'),
    });
    for (const sprint of release.sprints || []) {
      const sprintTitle = `[Sprint] ${sprint.key} — ${sprint.title}`;
      specs.push({
        kind: 'sprint',
        title: sprintTitle,
        parentTitle: releaseTitle,
        milestone: release.milestone,
        release: release.key,
        sprint: sprint.key,
        body: [
          `# Sprint ${sprint.key} — ${sprint.title}`,
          '',
          `**Release:** ${release.key}  •  **Estimate:** ${sprint.estimate || 'TBD'}`,
          '',
          '## Sprint goal',
          '',
          '- Skeleton generated by bootstrap. Fill goal/tasks/exit criteria before kickoff.',
          '',
          '## Scope / tasks',
          '',
          ...((sprint.tasks || []).map((task) => `- [ ] ${task}`).join('\n') || ['- TBD']),
          '',
          '## Exit criteria / demo',
          '',
          '- [ ] All child tasks Done or explicitly deferred',
          '- [ ] Evidence posted',
          '- [ ] Parent release tracker updated',
          '',
        ].join('\n'),
      });
      for (const task of sprint.tasks || []) {
        specs.push({
          kind: 'task',
          title: `[Task] ${task}`,
          parentTitle: sprintTitle,
          milestone: release.milestone,
          release: release.key,
          sprint: sprint.key,
          body: [
            `# Task — ${task}`,
            '',
            '## Why / context',
            '',
            '- Skeleton generated by bootstrap.',
            '',
            '## Current behavior',
            '',
            '- Fill current behavior/evidence.',
            '',
            '## Goal',
            '',
            '- Fill the concrete outcome.',
            '',
            '## Non-goals',
            '',
            '- Fill out-of-scope items.',
            '',
            '## Acceptance criteria',
            '',
            '- [ ] Fill a testable criterion.',
            '',
            '## Test plan',
            '',
            '- [ ] Fill commands/checks.',
            '',
            '## Verification evidence required',
            '',
            '- Fill evidence expected at check-out.',
            '',
            '## Dependencies / blockers',
            '',
            '- None.',
            '',
            '## Risks / rollback',
            '',
            '- Fill risks/rollback.',
            '',
            '## Estimate',
            '',
            '- S / M / L (fill).',
            '',
          ].join('\n'),
        });
      }
    }
  }
  return specs;
}

function fieldColor(name) {
  if (name === 'risk:low') return '0e8a16';
  if (name === 'risk:medium' || name === 'status:needs-triage') return 'fbca04';
  if (name === 'risk:high') return 'd93f0b';
  if (name === 'plan-change') return '1d76db';
  if (name === 'source:downstream') return '0e8a16';
  return 'ededed';
}

function labelDescription(name) {
  if (name.startsWith('risk:')) return 'Tracker risk label';
  if (name === 'plan-change') return 'Scope/estimate/gate change';
  if (name === 'source:downstream') return 'Downstream feedback origin';
  if (name === 'status:needs-triage') return 'Downstream intake awaiting triage';
  return 'Tracker process label';
}

function issueKindType(_kind) {
  return 'Task';
}

export async function runBootstrap({ config, github, apply = false, logger = console }) {
  const errors = validateConfig(config);
  if (errors.length) {
    const err = new Error(`Invalid tracker config:\n${errors.map((e) => `- ${e}`).join('\n')}`);
    err.code = 'CONFIG_INVALID';
    err.details = errors;
    throw err;
  }
  const [repoOwner, repoName] = config.repository.split('/');
  const owner = config.project.owner || repoOwner;
  const projectTitle = config.project.title;
  const actions = [];
  const warnings = [];
  const add = (line) => {
    actions.push(line);
    if (!apply) logger.log(line);
  };

  // Project.
  let project = (await github.listProjects(owner)).find((p) => p.title === projectTitle) || null;
  if (!project) {
    add(`CREATE project "${projectTitle}" (owner ${owner})`);
    if (apply) project = await github.createProject(owner, projectTitle);
    else project = { number: null, id: null, title: projectTitle };
  }
  if (project?.number) {
    add(`ENSURE project #${project.number} linked to ${config.repository}`);
    if (apply) {
      try {
        await github.linkProject(owner, project.number, config.repository);
      } catch (err) {
        warnings.push(`project link: ${err.message}`);
      }
    }
  } else if (apply) {
    throw new Error('project creation did not return a project number');
  }

  // Fields. Status comes from config.statuses; the rest from config.fields.
  let fields = project?.number ? await github.listFields(owner, project.number) : [];
  const fieldMap = () => new Map(fields.map((f) => [f.name, f]));
  const defaultOption = (fieldName, preferred) => {
    const field = fieldMap().get(fieldName);
    if (!field?.options?.length) return null;
    return field.options.find((option) => option.name === preferred)?.name || field.options[0].name;
  };
  const configuredFields = {
    Status: { options: config.statuses || [] },
    ...(config.fields || {}),
  };
  for (const [fieldName, fieldConfig] of Object.entries(configuredFields)) {
    const options = fieldConfig.options || [];
    const field = fieldMap().get(fieldName);
    if (!field) {
      add(`CREATE field "${fieldName}" → ${options.join(', ')}`);
      if (apply) {
        await github.createField(owner, project.number, fieldName, options);
        fields = await github.listFields(owner, project.number);
      }
    } else {
      const existing = new Set((field.options || []).map((o) => o.name));
      const missing = options.filter((name) => !existing.has(name));
      if (missing.length) {
        add(`ADD options to "${fieldName}": ${missing.join(', ')}`);
        if (apply) {
          await github.updateFieldOptions(field.id, [...(field.options || []).map((o) => o.name), ...missing]);
          fields = await github.listFields(owner, project.number);
        }
      }
    }
  }

  // Skeleton issues must satisfy DoR/audit: seed valid defaults for required fields.
  const issueDefaults = {
    Area: defaultOption('Area'),
    Kind: defaultOption('Kind'),
    Estimate: defaultOption('Estimate', 'M'),
  };

  // Milestones.
  const milestones = (await github.listMilestones(repoOwner, repoName)) || [];
  const milestoneByTitle = new Map(milestones.map((m) => [m.title, m]));
  for (const release of config.releases || []) {
    if (!milestoneByTitle.has(release.milestone)) {
      add(`CREATE milestone "${release.milestone}"`);
      if (apply) {
        const created = await github.createMilestone(repoOwner, repoName, release.milestone, `Release ${release.key}`);
        milestoneByTitle.set(release.milestone, created);
      }
    }
  }

  // Labels.
  const labels = (await github.listLabels(repoOwner, repoName)) || [];
  const existingLabels = new Set(labels.map((label) => label.name));
  for (const name of [...(config.labels?.risk || []), ...(config.labels?.process || [])]) {
    if (!existingLabels.has(name)) {
      add(`CREATE label "${name}"`);
      if (apply) await github.createLabel(repoOwner, repoName, name, fieldColor(name), labelDescription(name));
    }
  }

  // Issues.
  const specs = buildIssueSpecs(config);
  const issueByTitle = new Map();
  const projectItems = project?.number && apply ? await github.listProjectItems(owner, project.number) : [];
  const itemsByIssue = new Map((projectItems || []).map((item) => [item.content?.number, item]));

  for (const spec of specs) {
    let issue = await github.findIssue(repoOwner, repoName, spec.title);
    if (!issue) {
      add(`CREATE issue "${spec.title}"`);
      if (apply) {
        issue = await github.createIssue(repoOwner, repoName, {
          title: spec.title,
          body: spec.body,
          milestone: spec.milestone,
        });
      } else {
        issue = { number: null, title: spec.title, state: 'OPEN', url: null };
      }
    } else if (issue.state === 'CLOSED') {
      warnings.push(`existing issue "${spec.title}" is closed; not recreating it`);
    }
    issueByTitle.set(spec.title, issue);
    if (apply && issue.number) {
      try {
        await github.setIssueType(repoOwner, repoName, issue.number, issueKindType(spec.kind));
      } catch (err) {
        warnings.push(`issue type ${spec.title}: ${err.message}`);
      }
      if (project?.number) {
        const desired = {
          Status: 'Todo',
          Release: spec.release,
          Sprint: spec.sprint,
          Source: 'Internal',
          ...issueDefaults,
        };
        let item = itemsByIssue.get(issue.number);
        if (!item) {
          add(`ADD issue #${issue.number} to project`);
          item = await github.addProjectItem(owner, project.number, issue.url);
          itemsByIssue.set(issue.number, item);
        }
        for (const [fieldName, value] of Object.entries(desired)) {
          if (!value) continue;
          const field = fieldMap().get(fieldName);
          if (!field) continue;
          const option = (field.options || []).find((o) => o.name === value);
          if (!option) {
            warnings.push(`field ${fieldName}: option "${value}" not found; skipped for #${issue.number}`);
            continue;
          }
          const current = item[fieldName.toLowerCase()];
          if (current === value) continue;
          add(`SET #${issue.number} ${fieldName}=${value}`);
          await github.setProjectItemField(project.id, item.id, field.id, option.id);
        }
      }
    }
    if (spec.parentTitle) {
      const parent = issueByTitle.get(spec.parentTitle);
      if (apply && parent?.number && issue.number) {
        const existingChildren = await github.listSubIssues(repoOwner, repoName, parent.number);
        if (!existingChildren.some((child) => child.number === issue.number)) {
          add(`LINK #${issue.number} under #${parent.number}`);
          await github.addSubIssue(repoOwner, repoName, parent.number, issue.number);
        }
      } else {
        add(`LINK sub-issue "${spec.title}" under "${spec.parentTitle}"`);
      }
    }
  }

  const manual = [
    'Create/verify views in the GitHub UI: In flight, Current sprint, Roadmap, Blocked, Release readiness, Recently done, Downstream.',
    'Enable project workflows: auto-add repo issues; issue closed → Done. Do not auto-start work.',
    'Configure branch protection/required checks and protect release tags/environments.',
    'Create the GitHub App/project token for audit (keep it as a secret; never in config).',
    'Run `node scripts/github/audit.mjs --config tracker.config.json --advisory` (strict for release gates) and record accepted exceptions.',
  ];
  const result = {
    ok: true,
    mode: apply ? 'apply' : 'dry-run',
    project: project ? { number: project.number, title: project.title, id: project.id } : null,
    repository: config.repository,
    actions,
    warnings,
    manual,
  };
  if (!apply) {
    logger.log('');
    logger.log(`Dry-run: ${actions.length} planned action(s); no mutations performed.`);
    logger.log('Manual follow-ups:');
    for (const item of manual) logger.log(`- ${item}`);
  } else {
    logger.log(`Applied ${actions.length} action(s).`);
    for (const warning of warnings) logger.warn(`warning: ${warning}`);
  }
  return result;
}

function usage() {
  return [
    'Usage: node scripts/github/bootstrap.mjs --config tracker.config.json [--dry-run|--apply] [--json]',
    '',
    'Default: dry-run (no mutations).',
    '  --apply       Create/update project, fields, milestones, labels, issues, hierarchy',
    '  --dry-run     Explicitly show the plan (default)',
    '  --json        Print the plan/result as JSON',
    '  --help        Show this help',
  ].join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  (async () => {
    try {
      const args = parseArgs(process.argv.slice(2), {
        flags: ['apply', 'dry-run', 'json', 'help'],
        options: ['config'],
      });
      if (args.help) {
        console.log(usage());
        return;
      }
      if (args.apply && args['dry-run']) throw new UsageError('use either --apply or --dry-run, not both');
      const configPath = path.resolve(args.config || DEFAULT_CONFIG);
      if (!fs.existsSync(configPath)) throw new UsageError(`config not found: ${configPath}`);
      const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
      if (args.json) {
        const logs = [];
        const result = await runBootstrap({
          config,
          github: createGitHub(),
          apply: Boolean(args.apply),
          logger: { log: (m) => logs.push(m), warn: (m) => logs.push(m), error: (m) => logs.push(m) },
        });
        process.stdout.write(`${JSON.stringify({ ...result, logs }, null, 2)}\n`);
      } else {
        await runBootstrap({ config, github: createGitHub(), apply: Boolean(args.apply) });
      }
    } catch (err) {
      console.error(`error: ${err.message}`);
      process.exitCode = 1;
    }
  })();
}
