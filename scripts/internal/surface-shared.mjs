#!/usr/bin/env node
/**
 * Shared repo-surface constants and deterministic renderers.
 *
 * Used by:
 *   - scripts/internal/verify-surface.mjs  (guard: class/status lists, generated catalog block comparison)
 *   - scripts/internal/render-surface.mjs  (CLI: renders docs/SURFACE.md from the manifest)
 *   - tests/verify-surface.test.mjs        (renderer/guard agreement)
 *
 * Template-maintainer tooling (never copied into adopting projects). The renderers are pure
 * functions over a parsed manifest, so the CLI, the guard, and the tests cannot disagree about the
 * generated text. Output is deterministic: fixed class order (CLASSES), then path sort; no
 * timestamps, no environment-dependent values.
 */

/** Classification classes, in canonical display order. */
export const CLASSES = [
  'reusable-workflow',
  'reusable-action',
  'copy-mode',
  'adopter-cli',
  'adopter-lib',
  'internal',
  'generated',
];

/** Resolved statuses. `shipped` means the classified file exists; `contract-only` means it is documented only. */
export const STATUSES = ['shipped', 'contract-only'];

/** Entry audiences. */
export const AUDIENCES = ['template', 'adopter'];

/** Provenance marker rendered at the top of every generated surface artifact. */
export const GENERATED_MARKER =
  '<!-- Generated by `node scripts/internal/render-surface.mjs` from `contract/repo-surface.json`. Do not edit by hand. -->';

/** Delimiters of the generated availability block in docs/ACTIONS_CATALOG.md. */
export const CATALOG_STATUS_START_MARKER = '<!-- surface-status:start -->';
export const CATALOG_STATUS_END_MARKER = '<!-- surface-status:end -->';

/** Human guidance for each class, rendered in docs/SURFACE.md's class map. */
export const CLASS_GUIDE = {
  'reusable-workflow': {
    meaning: 'Reusable `workflow_call` contract workflows',
    locations: '.github/workflows/reusable-*.yml',
  },
  'reusable-action': {
    meaning: 'Reusable composite actions',
    locations: '.github/actions/<name>/action.yml',
  },
  'copy-mode': {
    meaning: 'Non-runnable copy examples/templates (GitHub executes only `.github/workflows/`)',
    locations: 'profiles/**',
  },
  'adopter-cli': {
    meaning: 'CLI entrypoints copied into adopting repositories',
    locations: 'scripts/adopt/cli/** · scripts/adopt/docs/**',
  },
  'adopter-lib': {
    meaning: 'Shared libraries copied into adopting repositories',
    locations: 'scripts/adopt/lib/**',
  },
  internal: {
    meaning: 'Template-internal tooling/docs (never copied)',
    locations: 'scripts/internal/** · docs/** · contract/** · .github/** (non-reusable) · profiles/**/README.md',
  },
  generated: {
    meaning: 'Generated files (do not edit by hand)',
    locations: 'manifest `generatedRoots`',
  },
};

// ---------------------------------------------------------------------------
// Helpers (shared path/entry normalization)
// ---------------------------------------------------------------------------

function normalizePath(value) {
  return String(value).replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, '');
}

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

/** Paths classified by one manifest entry (exactly one of `path`/`paths` is present). */
export function entryPaths(entry) {
  if (typeof entry?.path === 'string') return [normalizePath(entry.path)];
  return asArray(entry?.paths).map(normalizePath);
}

/** Locale-independent string sort (stable across machines). */
function compareStrings(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function codeSpan(value) {
  return `\`${String(value)}\``;
}

function escapeTableCell(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
}

function renderTableCell(value) {
  return escapeTableCell(value);
}

// ---------------------------------------------------------------------------
// Generated catalog availability block (docs/ACTIONS_CATALOG.md §2)
// ---------------------------------------------------------------------------

/**
 * Render the token for one reusable workflow/action entry as used in the catalog block:
 * - reusable-workflow -> workflow filename (`reusable-ci.yml`)
 * - reusable-action   -> action directory name (`setup-node-cache`)
 */
export function catalogStatusToken(entry) {
  const rel = entryPaths(entry)[0] ?? '';
  if (!rel) return String(entry?.id ?? '');
  const parts = rel.split('/');
  if (entry.class === 'reusable-action') {
    const actionsIndex = parts.indexOf('actions');
    const name = actionsIndex >= 0 ? parts[actionsIndex + 1] : '';
    if (name && name !== 'action.yml') return name;
  }
  return parts[parts.length - 1];
}

function catalogStatusTokens(entries) {
  return entries
    .filter((entry) => entry && ['reusable-workflow', 'reusable-action'].includes(entry.class))
    .map((entry) => catalogStatusToken(entry))
    .sort(compareStrings);
}

function renderTokenList(tokens) {
  return tokens.length ? tokens.map(codeSpan).join(', ') : '`(none)`';
}

/**
 * Render the generated availability block for docs/ACTIONS_CATALOG.md.
 * Lists every reusable workflow + composite action with its manifest status, sorted.
 * Includes its own markers so callers can splice it verbatim.
 */
export function renderCatalogStatusBlock(entries = []) {
  const reusable = asArray(entries);
  const shipped = catalogStatusTokens(reusable.filter((entry) => entry?.status === 'shipped'));
  const contractOnly = catalogStatusTokens(reusable.filter((entry) => entry?.status === 'contract-only'));
  return [
    CATALOG_STATUS_START_MARKER,
    GENERATED_MARKER,
    '**Shipped vs contract-only (generated from `contract/repo-surface.json`):**',
    `- shipped: ${renderTokenList(shipped)}`,
    `- contract-only: ${renderTokenList(contractOnly)}`,
    CATALOG_STATUS_END_MARKER,
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Generated docs/SURFACE.md
// ---------------------------------------------------------------------------

function sortedEntries(entries) {
  return asArray(entries)
    .map((entry, index) => ({ entry, index }))
    .sort((a, b) => {
      const aPath = entryPaths(a.entry)[0] ?? '';
      const bPath = entryPaths(b.entry)[0] ?? '';
      return compareStrings(aPath, bPath) || a.index - b.index;
    })
    .map((item) => item.entry);
}

function classRows(entries, klass) {
  return sortedEntries(entries)
    .filter((entry) => entry.class === klass)
    .flatMap((entry) =>
      entryPaths(entry).map((rel) => ({
        path: rel,
        entry,
      })),
    )
    .sort((a, b) => compareStrings(a.path, b.path));
}

function renderClassMapRows({ entries, manifest }) {
  const rows = [];
  for (const klass of CLASSES) {
    const guide = CLASS_GUIDE[klass];
    const inClass = entries.filter((entry) => entry.class === klass);
    const locations =
      klass === 'generated'
        ? asArray(manifest?.generatedRoots)
            .map((root) => codeSpan(String(root)))
            .join(' · ') || '`(none)`'
        : guide.locations;
    rows.push(
      `| ${codeSpan(klass)} | ${renderTableCell(guide.meaning)} | ${renderTableCell(locations)} | ${inClass.length} | ${
        inClass.filter((entry) => entry.status === 'shipped').length
      } | ${inClass.filter((entry) => entry.status === 'contract-only').length} |`,
    );
  }
  return rows;
}

function renderEntriesSection(entries) {
  const lines = [];
  for (const klass of CLASSES) {
    const rows = classRows(entries, klass);
    lines.push(`### ${klass}`, '');
    if (!rows.length) {
      lines.push('No entries.', '');
      continue;
    }
    const shippedPaths = rows.filter((row) => row.entry.status === 'shipped').length;
    const contractOnlyPaths = rows.filter((row) => row.entry.status === 'contract-only').length;
    lines.push(`${rows.length} path(s) · ${shippedPaths} shipped · ${contractOnlyPaths} contract-only.`, '');
    lines.push('| Path | Status | Audience | Title | Catalog § | Docs |');
    lines.push('|---|---|---|---|---|---|');
    for (const row of rows) {
      const entry = row.entry;
      lines.push(
        `| ${codeSpan(row.path)} | ${entry.status} | ${renderTableCell(asArray(entry.audience).join(', ') || '—')} | ${renderTableCell(
          entry.title ?? '',
        )} | ${renderTableCell(entry.catalogSection ?? '—')} | ${renderTableCell(
          asArray(entry.docs).map(codeSpan).join('<br>') || '—',
        )} |`,
      );
    }
    lines.push('');
  }
  return lines;
}

function renderContractOnlyGaps(entries) {
  const gaps = sortedEntries(entries.filter((entry) => entry.status === 'contract-only'));
  if (!gaps.length) return ['No contract-only entries.', ''];
  const lines = ['| Entry | Path | Note / next task |', '|---|---|---|'];
  for (const entry of gaps) {
    const target = entryPaths(entry)
      .map((rel) => codeSpan(rel))
      .join('<br>');
    lines.push(`| ${codeSpan(entry.id)} | ${target} | ${renderTableCell(entry.note ?? entry.nextTask ?? '—')} |`);
  }
  lines.push('');
  return lines;
}

function renderGeneratedArtifacts(entries) {
  const generated = sortedEntries(entries.filter((entry) => entry.class === 'generated'));
  if (!generated.length) return ['No generated entries.', ''];
  const lines = [
    'Files below are build outputs. Never edit them by hand: change the source input and re-run the',
    'generator; the `--check` gates fail on drift.',
    '',
  ];
  for (const entry of generated) {
    const paths = entryPaths(entry);
    const first = paths[0] ?? '(no path)';
    const more = paths.length > 1 ? ` (+${paths.length - 1} more file(s))` : '';
    lines.push(`- ${codeSpan(first)}${more} — generator: ${codeSpan(entry.generatedBy ?? '(not declared)')}`);
  }
  lines.push('');
  return lines;
}

/**
 * Render the complete generated docs/SURFACE.md content.
 *
 * @param {{manifest: object, trackerVersion: string}} options
 * @returns {string} Markdown ending in exactly one newline (byte-stable for --check).
 */
export function renderSurfaceDoc({ manifest, trackerVersion } = {}) {
  const entries = asArray(manifest?.entries);
  const paths = entries.reduce((total, entry) => total + entryPaths(entry).length, 0);
  const shipped = entries.filter((entry) => entry.status === 'shipped').length;
  const contractOnly = entries.filter((entry) => entry.status === 'contract-only').length;
  const version = String(trackerVersion ?? '').replace(/^v/, '');
  const lines = [
    GENERATED_MARKER,
    '',
    '# Repository surface',
    '',
    `**Tracker version:** v${version} · **Source:** \`contract/repo-surface.json\` · **Renderer:** \`node scripts/internal/render-surface.mjs\``,
    '',
    '> Generated file. Edit `contract/repo-surface.json` and run `npm run surface:render`; the',
    '> `render-surface --check` gate fails when this file is stale. Do not edit by hand.',
    '',
    '## Summary',
    '',
    '| Metric | Count |',
    '|---|---|',
    `| Entries | ${entries.length} |`,
    `| Paths | ${paths} |`,
    `| Shipped | ${shipped} |`,
    `| Contract-only | ${contractOnly} |`,
    '',
    '## Class map',
    '',
    '| Class | Meaning | Allowed locations | Entries | Shipped | Contract-only |',
    '|---|---|---|---|---|---|',
    ...renderClassMapRows({ entries, manifest }),
    '',
    '## Entries by class',
    '',
    ...renderEntriesSection(entries),
    '## Contract-only gaps',
    '',
    ...renderContractOnlyGaps(entries),
    '## Generated artifacts',
    '',
    ...renderGeneratedArtifacts(entries),
  ];
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}
