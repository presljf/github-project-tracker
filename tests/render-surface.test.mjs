test('spliceCatalogStatusBlock replaces only the generated block', () => {
  const catalog = ['before', CATALOG_STATUS_START_MARKER, 'stale', CATALOG_STATUS_END_MARKER, 'after'].join('\n');
  const block = renderCatalogStatusBlock([]);
  const result = spliceCatalogStatusBlock(catalog, block);
  assert.equal(result.ok, true);
  assert.match(result.text, /^before\n<!-- surface-status:start -->/);
  assert.match(result.text, /\n<!-- surface-status:end -->\nafter$/);
  assert.ok(!result.text.includes('stale'));
});

test('spliceCatalogStatusBlock reports missing, duplicate, and misordered markers', () => {
  const block = renderCatalogStatusBlock([]);
  assert.equal(spliceCatalogStatusBlock('no markers here', block).reason, 'missing-markers');
  const duplicate = [CATALOG_STATUS_START_MARKER, CATALOG_STATUS_START_MARKER, CATALOG_STATUS_END_MARKER].join('\n');
  assert.equal(spliceCatalogStatusBlock(duplicate, block).reason, 'duplicate-markers');
  const misordered = [CATALOG_STATUS_END_MARKER, CATALOG_STATUS_START_MARKER].join('\n');
  assert.equal(spliceCatalogStatusBlock(misordered, block).reason, 'misordered-markers');
});

test('extract/normalize helpers are stable', () => {
  assert.equal(extractCatalogStatusBlock('no block'), null);
  const block = renderCatalogStatusBlock([
    { id: 'wf:x', path: '.github/workflows/reusable-x.yml', class: 'reusable-workflow', status: 'shipped' },
  ]);
  assert.equal(extractCatalogStatusBlock(`pre\n${block}\npost`), block);
  assert.equal(normalizeCatalogStatusBlock('a  \r\nb\t'), 'a\nb');
  assert.equal(normalizeCatalogStatusBlock(''), '');
});

test('buildSurfaceOutputs includes the shared catalog block for the manifest', () => {
  const root = fixture({ write: false });
  try {
    const built = buildSurfaceOutputs({ root });
    const manifest = JSON.parse(readFixtureText(root, 'contract/repo-surface.json'));
    assert.equal(built.catalog.present, true);
    assert.equal(built.catalog.expectedBlock, renderCatalogStatusBlock(manifest.entries));
    assert.ok(built.catalog.updatedText.includes(built.catalog.expectedBlock));
    assert.ok(built.doc.startsWith('<!-- Generated by `node scripts/internal/render-surface.mjs`'));
  } finally {
    cleanup(root);
  }
});

