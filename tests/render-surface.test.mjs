/* Tests for scripts/internal/render-surface.mjs: docs/SURFACE.md + the generated
 * docs/ACTIONS_CATALOG.md surface-status block. All write-mode exercise happens on temp copies;
 * the repository's committed docs are never rewritten by tests.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import {
  buildSurfaceOutputs,
  extractCatalogStatusBlock,
  normalizeCatalogStatusBlock,
  spliceCatalogStatusBlock,
} from '../scripts/internal/render-surface.mjs';
import {
  CATALOG_STATUS_END_MARKER,
  CATALOG_STATUS_START_MARKER,
  renderCatalogStatusBlock,
} from '../scripts/internal/surface-shared.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RENDERER = path.join(ROOT, 'scripts', 'internal', 'render-surface.mjs');
const SURFACE = 'docs/SURFACE.md';
const CATALOG = 'docs/ACTIONS_CATALOG.md';

function runRenderer(args, cwd = ROOT) {
  return spawnSync(process.execPath, [RENDERER, ...args], {
    cwd,
    encoding: 'utf8',
    env: { PATH: process.env.PATH, HOME: process.env.HOME },
  });
}

function copyFile(rel, root) {
  const target = path.join(root, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(path.join(ROOT, rel), target);
}

/** Temp root with the real manifest/config/catalog and freshly rendered SURFACE.md. */
function fixture({ write = true } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'render-surface-'));
  copyFile('contract/repo-surface.json', root);
  copyFile('tracker.config.json', root);
  copyFile(CATALOG, root);
  if (write) {
    const result = runRenderer(['--root', root, '--write']);
    assert.equal(result.status, 0, result.stderr);
  }
  return root;
}

function readFixtureText(root, rel) {
  return fs.readFileSync(path.join(root, rel), 'utf8');
}

function cleanup(root) {
  fs.rmSync(root, { recursive: true, force: true });
}

