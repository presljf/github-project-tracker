test('--write creates both artifacts and a fresh --check passes', () => {
  const root = fixture({ write: false });
  try {
    const write = runRenderer(['--root', root, '--write']);
    assert.equal(write.status, 0, write.stderr);
    assert.match(write.stdout, /Wrote docs\/SURFACE\.md/);
    assert.match(write.stdout, /Updated docs\/ACTIONS_CATALOG\.md generated surface-status block/);
    assert.ok(fs.existsSync(path.join(root, SURFACE)));

    const check = runRenderer(['--root', root, '--check']);
    assert.equal(check.status, 0, check.stderr);
    assert.match(check.stdout, /docs\/SURFACE\.md is up to date/);
    assert.match(check.stdout, /docs\/ACTIONS_CATALOG\.md surface-status block is up to date/);
  } finally {
    cleanup(root);
  }
});

test('second --write is byte-identical (idempotent)', () => {
  const root = fixture();
  try {
    const surfaceBefore = readFixtureText(root, SURFACE);
    const catalogBefore = readFixtureText(root, CATALOG);
    const again = runRenderer(['--root', root, '--write']);
    assert.equal(again.status, 0, again.stderr);
    assert.equal(readFixtureText(root, SURFACE), surfaceBefore);
    assert.equal(readFixtureText(root, CATALOG), catalogBefore);
  } finally {
    cleanup(root);
  }
});

test('SURFACE drift fails --check with the existing message and --write repairs it', () => {
  const root = fixture();
  try {
    fs.appendFileSync(path.join(root, SURFACE), '\nstale edit\n');
    const stale = runRenderer(['--root', root, '--check']);
    assert.equal(stale.status, 1);
    assert.match(stale.stderr, /docs\/SURFACE\.md is stale/);
    assert.match(stale.stderr, /first difference at docs\/SURFACE\.md:\d+/);

    const repair = runRenderer(['--root', root, '--write']);
    assert.equal(repair.status, 0, repair.stderr);
    assert.equal(runRenderer(['--root', root, '--check']).status, 0);
  } finally {
    cleanup(root);
  }
});

test('catalog surface-status block drift fails --check with a distinct message and --write repairs it', () => {
  const root = fixture();
  try {
    const catalogFile = path.join(root, CATALOG);
    const tampered = readFixtureText(root, CATALOG).replace('- shipped:', '- shipped (stale):');
    assert.notEqual(tampered, readFixtureText(root, CATALOG));
    fs.writeFileSync(catalogFile, tampered);

    const stale = runRenderer(['--root', root, '--check']);
    assert.equal(stale.status, 1);
    assert.match(stale.stderr, /docs\/ACTIONS_CATALOG\.md surface-status block is stale/);
    assert.ok(!stale.stderr.includes('docs/SURFACE.md is stale'), 'SURFACE is still fresh');
    assert.match(stale.stderr, /first difference in the docs\/ACTIONS_CATALOG\.md surface-status block/);

    const repair = runRenderer(['--root', root, '--write']);
    assert.equal(repair.status, 0, repair.stderr);
    assert.match(readFixtureText(root, CATALOG), /- shipped: /);
    assert.equal(runRenderer(['--root', root, '--check']).status, 0);
  } finally {
    cleanup(root);
  }
});

test('missing catalog markers are a blocking error for --check and --write (no partial writes)', () => {
  const root = fixture();
  try {
    const catalogFile = path.join(root, CATALOG);
    fs.writeFileSync(catalogFile, readFixtureText(root, CATALOG).replace(CATALOG_STATUS_START_MARKER, ''));
    const surfaceBefore = readFixtureText(root, SURFACE);

    const check = runRenderer(['--root', root, '--check']);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /missing the <!-- surface-status:start -->/);

    const write = runRenderer(['--root', root, '--write']);
    assert.equal(write.status, 1);
    assert.match(write.stderr, /missing the <!-- surface-status:start -->/);
    assert.equal(readFixtureText(root, SURFACE), surfaceBefore, 'no partial SURFACE write on marker failure');
  } finally {
    cleanup(root);
  }
});

test('duplicate catalog markers are a blocking error', () => {
  const root = fixture();
  try {
    const catalogFile = path.join(root, CATALOG);
    fs.appendFileSync(catalogFile, `\n${CATALOG_STATUS_START_MARKER}\n${CATALOG_STATUS_END_MARKER}\n`);
    const check = runRenderer(['--root', root, '--check']);
    assert.equal(check.status, 1);
    assert.match(check.stderr, /exactly one <!-- surface-status:start -->/);
  } finally {
    cleanup(root);
  }
});

test('a root without docs/ACTIONS_CATALOG.md skips the block with a notice', () => {
  const root = fixture({ write: false });
  try {
    fs.rmSync(path.join(root, CATALOG));
    const write = runRenderer(['--root', root, '--write']);
    assert.equal(write.status, 0, write.stderr);
    assert.match(write.stderr, /docs\/ACTIONS_CATALOG\.md not found; skipped generated surface-status block sync/);
    const check = runRenderer(['--root', root, '--check']);
    assert.equal(check.status, 0, check.stderr);
    assert.match(check.stderr, /docs\/ACTIONS_CATALOG\.md not found; skipping/);
  } finally {
    cleanup(root);
  }
});

test('--stdout prints SURFACE only and writes nothing', () => {
  const root = fixture({ write: false });
  try {
    const catalogBefore = readFixtureText(root, CATALOG);
    const result = runRenderer(['--root', root, '--stdout']);
    assert.equal(result.status, 0, result.stderr);
    assert.ok(result.stdout.startsWith('<!-- Generated by `node scripts/internal/render-surface.mjs`'));
    assert.ok(!fs.existsSync(path.join(root, SURFACE)));
    assert.equal(readFixtureText(root, CATALOG), catalogBefore);
  } finally {
    cleanup(root);
  }
});

test('CLI usage errors stay exit 2', () => {
  const conflict = runRenderer(['--check', '--stdout']);
  assert.equal(conflict.status, 2);
  assert.match(conflict.stderr, /only one of --check, --stdout, --write/);

  const unknown = runRenderer(['--nope']);
  assert.equal(unknown.status, 2);

  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'render-surface-empty-'));
  try {
    const missing = runRenderer(['--root', root, '--check']);
    assert.equal(missing.status, 2);
    assert.match(missing.stderr, /cannot read manifest/);
  } finally {
    cleanup(root);
  }

  const help = runRenderer(['--help']);
  assert.equal(help.status, 0);
  assert.match(help.stdout, /Usage: node scripts\/internal\/render-surface\.mjs/);
});
